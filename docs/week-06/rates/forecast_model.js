/* Frontend-only transformation of the published fitted statistical model.
   Historical observations and fitted parameters are generated by Python.
   The user supplies only a one-time conditional policy deviation. */
(function(root,factory){
  "use strict";
  const model=factory();
  if(typeof module!=="undefined"&&module.exports)module.exports=model;
  if(root)root.ForecastModel=model;
})(typeof window!=="undefined"?window:null,function(){
  "use strict";
  const METRICS=["5y","10y","spread"];
  function verify(data){
    if(!data||data.status!=="ready"||data.schema_version!==2||
       !Array.isArray(data.observations)||data.observations.length<145||
       !Array.isArray(data.forecast)||data.forecast.length!==25||
       !data.empirical_error_bands||!data.backtest||
       !Array.isArray(data.backtest.metrics)||data.backtest.metrics.length<9){
      throw new Error("No complete calibrated forecasting snapshot available.");
    }
    const current=data.observations.at(-1);
    if(data.forecast[0].date!==current.date||
      Math.abs(data.forecast[0].y5-current.dgs5)>0.0002||
      Math.abs(data.forecast[0].y10-current.dgs10)>0.0002){
      throw new Error("The forecast origin does not match the verified observations.");
    }
    for(const key of METRICS){
      const bands=data.empirical_error_bands[key];
      if(!Array.isArray(bands)||bands.length!==24||
         bands.some((b,i)=>b.month!==i+1||b.sample_count<25||
           !Number.isFinite(b.error_p10_pp)||!Number.isFinite(b.error_p90_pp)||
           b.error_p10_pp>b.error_p90_pp)){
        throw new Error("Rolling error calibration is absent or invalid for "+key);
      }
    }
    for(const [i,row] of data.forecast.entries()){
      if(row.month!==i||![row.y5,row.y10,row.spread,
        row.effect5_per_1pp,row.effect10_per_1pp].every(Number.isFinite)){
        throw new Error("Invalid fitted forecast row "+i);
      }
    }
    return data;
  }
  function forecast(data, rateDeviationBp, horizon){
    verify(data);
    const delta=Number(rateDeviationBp),length=Number(horizon);
    if(!Number.isFinite(delta)||Math.abs(delta)>100||
       ![6,12,24].includes(length)){
      throw new Error("Unsupported policy deviation or forecasting horizon.");
    }
    const shock=delta/100;
    return data.forecast.slice(0,length+1).map((row,h)=>{
      const five=row.y5+row.effect5_per_1pp*shock;
      const ten=row.y10+row.effect10_per_1pp*shock;
      const spread=ten-five;
      const error5=h?data.empirical_error_bands["5y"][h-1]:null;
      const error10=h?data.empirical_error_bands["10y"][h-1]:null;
      const errorSpread=h?data.empirical_error_bands.spread[h-1]:null;
      return {
        date:row.date,month:h,y5:five,y10:ten,spread,
        low5:five+(error5?error5.error_p10_pp:0),
        high5:five+(error5?error5.error_p90_pp:0),
        low10:ten+(error10?error10.error_p10_pp:0),
        high10:ten+(error10?error10.error_p90_pp:0),
        lowSpread:spread+(errorSpread?errorSpread.error_p10_pp:0),
        highSpread:spread+(errorSpread?errorSpread.error_p90_pp:0),
      };
    });
  }
  function history(data,value){
    verify(data);
    if(value==="all")return data.observations;
    const months=Number(value);
    if(![12,24,60,120,180,240].includes(months))throw new Error("Invalid history selection");
    return data.observations.slice(-months);
  }
  return {verify,forecast,history};
});
